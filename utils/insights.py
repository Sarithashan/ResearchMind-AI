"""Grounded analysis of an uploaded paper.

Nothing here is generated by a neural network: every output is text copied from the paper.
"""
import math
import re
from collections import Counter

STOP = set(
    "a an the of to in on for and or is are was were be been by with as at from that this "
    "these those it its we our us can may which have has had not no but also than then there "
    "their they them such using used use into over under between within what who how does do "
    "paper research".split()
)

CUES = {
    "objective": ["in this paper", "in this work", "in this study", "we propose", "we present",
                  "we introduce", "this paper presents", "this paper proposes", "we aim",
                  "the aim of", "the goal of", "the objective", "we investigate", "we study"],
    "method": ["we use", "we used", "we train", "we trained", "our method", "our approach",
               "our model", "the proposed", "we implement", "we employ", "we apply",
               "we adopt", "architecture", "is based on", "dataset", "we evaluate"],
    "findings": ["we find", "we found", "results show", "our results", "we show that",
                 "we observe", "we demonstrate", "outperform", "achieve", "improves",
                 "improvement", "significantly", "experiments show", "we obtain"],
    "conclusion": ["we conclude", "in conclusion", "to conclude", "in summary", "overall"],
    "limitations": ["limitation", "limited by", "however", "drawback", "shortcoming",
                    "not able", "cannot", "future work", "left for future", "unable",
                    "fails to"],
}

SKIP = {"front", "references", "acknowledgements", "acknowledgments"}
_SENT_SPLIT = re.compile(r"(?<=[.!?])\s+(?=[A-Z0-9\[(])")
_WORD = re.compile(r"[a-z0-9]+")


def split_sentences(text):
    text = re.sub(r"\s+", " ", text).strip()
    return [s.strip() for s in _SENT_SPLIT.split(text) if 6 <= len(s.split()) <= 70]


def _top_by_cues(sections, names, cues, k):
    scored, order = [], 0
    for name in names:
        for s in split_sentences(sections.get(name, "")):
            low = s.lower()
            score = sum(1 for c in cues if c in low)
            if score > 0:
                scored.append((score, -order, s, name))
            order += 1
    scored.sort(reverse=True)
    return [(s, name) for _, _, s, name in scored[:k]]


def _present(sections, names, fallback):
    got = [n for n in names if n in sections and sections[n].strip()]
    return got or fallback


def extract_insights(sections, k=3):
    body = [n for n in sections if n not in SKIP]
    no_abstract = [n for n in body if n != "abstract"] or body
    out = {}

    out["Research objective"] = _top_by_cues(
        sections, _present(sections, ["abstract", "introduction"], body), CUES["objective"], k)
    out["Methodology"] = _top_by_cues(sections, no_abstract, CUES["method"], k)
    out["Key findings"] = _top_by_cues(
        sections,
        _present(sections, ["results", "discussion", "conclusion", "conclusions", "abstract"], body),
        CUES["findings"], k)

    concl = [n for n in ("conclusion", "conclusions") if n in sections and sections[n].strip()]
    if concl:
        out["Conclusion"] = [(s, concl[0]) for s in split_sentences(sections[concl[0]])[:k]]
    else:
        out["Conclusion"] = _top_by_cues(sections, body, CUES["conclusion"], k)

    if "limitations" in sections and sections["limitations"].strip():
        out["Limitations (where identifiable)"] = [
            (s, "limitations") for s in split_sentences(sections["limitations"])[:k]]
    else:
        out["Limitations (where identifiable)"] = _top_by_cues(
            sections, no_abstract, CUES["limitations"], k)
    return out


# ---------- Question answering by passage retrieval ----------
EXPANSIONS = {
    ("objective", "aim", "goal", "purpose", "motivation"):
        "propose present introduce aim goal study investigate",
    ("method", "approach", "technique"):
        "method approach model use propose train algorithm architecture",
    ("finding", "result", "outcome", "conclusion"):
        "results show find found achieve outperform demonstrate conclude",
    ("limitation", "weakness", "drawback", "shortcoming"):
        "limitation however cannot future limited drawback",
}


def build_passages(sections, size=3):
    def chunk(names):
        passages, pid = [], 0
        for name in names:
            sents = split_sentences(sections[name])
            for i in range(0, len(sents), size):
                pid += 1
                passages.append({"id": pid, "section": name,
                                 "text": " ".join(sents[i:i + size])})
        return passages

    names = [n for n in sections if n not in SKIP]
    return chunk(names) or chunk([n for n in sections if n != "references"])


def _tokens(text):
    return [w for w in _WORD.findall(text.lower()) if w not in STOP and len(w) > 1]


def retrieve(question, passages, k=3):
    """Rank passages by TF-IDF cosine similarity to the question."""
    if not passages:
        return []
    q = question.lower()
    extra = " ".join(words for keys, words in EXPANSIONS.items() if any(key in q for key in keys))
    docs = [_tokens(p["text"]) for p in passages]
    df = Counter(w for d in docs for w in set(d))
    n = len(docs)
    idf = {w: math.log((n + 1) / (c + 1)) + 1 for w, c in df.items()}

    def vec(tokens):
        tf = Counter(tokens)
        return {w: (1 + math.log(c)) * idf[w] for w, c in tf.items() if w in idf}

    qv = vec(_tokens(question + " " + extra))
    if not qv:
        return []
    qn = math.sqrt(sum(v * v for v in qv.values()))
    scored = []
    for p, d in zip(passages, docs):
        dv = vec(d)
        dn = math.sqrt(sum(v * v for v in dv.values()))
        if not dv or not dn:
            continue
        score = sum(v * dv.get(w, 0.0) for w, v in qv.items()) / (qn * dn)
        if score > 0:
            scored.append((score, p))
    scored.sort(key=lambda x: -x[0])
    return scored[:k]